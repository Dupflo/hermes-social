"""s13 (console ADR 038 §3) — shared keyword parity fixtures.

The JSON is generated by social/tools/keyword-parity/generate_keyword_parity.py from BOTH
keyword.py modules and copied verbatim into the console (test/fixtures/keyword-parity.json),
where the TikTok TS port is checked against the same expectations. The content fingerprint
below is pinned identically in both tools and in the console's Vitest test.
"""

import hashlib
import importlib.util
import json
from pathlib import Path

from app.keyword import contains_keyword

PARITY_DIR = Path(__file__).resolve().parents[2] / "keyword-parity"
PARITY_FILE = PARITY_DIR / "keyword-parity.json"
FINGERPRINT = "88ad8fdd9b6a9d63212e230f8c4fba7d7542a75a1ac35bea8c1734877dd86b08"
COLUMN = "meta"


def _data():
    return json.loads(PARITY_FILE.read_text(encoding="utf-8"))


def _fingerprint(data):
    lines = []
    for item in data["sets"]:
        for pair in item["pairs"]:
            lines.append(f"{item['name']}\t{pair['text']}\t{pair['keyword']}\t{int(pair['meta'])}\t{int(pair['tiktok'])}")
        for row in item["campaign"]:
            meta_index = "" if row["meta_index"] is None else str(row["meta_index"])
            tiktok_keyword = "" if row["tiktok_keyword"] is None else row["tiktok_keyword"]
            lines.append(f"{item['name']}\t{row['text']}\tC\t{meta_index}\t{tiktok_keyword}")
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def test_named_synthetic_sets_are_present():
    sets = {item["name"]: item for item in _data()["sets"]}
    assert len(sets["voicebox-ep10"]["keywords"]) == 18
    assert sets["voicebox-ep10"]["synthetic"] is True
    assert sets["systeme-ep8"]["synthetic"] is True
    assert "boundaries" in sets


def test_every_pair_matches_this_tool_expectation():
    for item in _data()["sets"]:
        for pair in item["pairs"]:
            assert contains_keyword(pair["text"], pair["keyword"]) is pair[COLUMN], (item["name"], pair)


def test_campaign_rows_match_this_tool_expectation():
    for item in _data()["sets"]:
        keywords = item["keywords"]
        for row in item["campaign"]:
            if COLUMN == "meta":
                found = next((i for i, kw in enumerate(keywords) if contains_keyword(row["text"], kw)), None)
                assert found == row["meta_index"], (item["name"], row)
            else:
                found = next((kw for kw in sorted(keywords) if contains_keyword(row["text"], kw)), None)
                assert found == row["tiktok_keyword"], (item["name"], row)


def test_fixtures_contain_divergent_and_nfd_cases():
    pairs = [pair for item in _data()["sets"] for pair in item["pairs"]]
    assert any(pair["meta"] != pair["tiktok"] for pair in pairs)
    assert any(pair["text"].startswith("sans ") and pair["meta"] != pair["tiktok"] for pair in pairs)
    assert any("́" in pair["text"] for pair in pairs)


def test_content_fingerprint_is_pinned():
    assert _fingerprint(_data()) == FINGERPRINT


def test_versioned_file_is_up_to_date(tmp_path):
    spec = importlib.util.spec_from_file_location("generate_keyword_parity", PARITY_DIR / "generate_keyword_parity.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    out = tmp_path / "keyword-parity.json"
    module.write(out)
    assert out.read_bytes() == PARITY_FILE.read_bytes()
